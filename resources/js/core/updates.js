// Update checks against GitHub Releases. Pure helpers (no DOM, no network)
// so they can be tested in Node; ui/updater.js does the fetching and UI.

export const REPO = 'macchie/motivo';
export const RELEASES_API = `https://api.github.com/repos/${REPO}/releases/latest`;
// Published by the Pages workflow; used when the API is rate-limited or blocked.
export const LATEST_JSON = 'https://macchie.github.io/motivo/latest.json';
export const RELEASES_PAGE = `https://github.com/${REPO}/releases/latest`;

// Release asset names are a contract with release.yml and the landing page.
export const ASSET_NAMES = {
  mac: 'Motivo-macOS.dmg',
  win: 'Motivo-Windows-x64.zip',
  'linux-x64': 'Motivo-Linux-x64.tar.gz',
  'linux-arm64': 'Motivo-Linux-arm64.tar.gz',
  'linux-armhf': 'Motivo-Linux-armhf.tar.gz',
};

// "v1.2.3-rc.1" → { nums: [1, 2, 3], pre: ['rc', 1] }
export function parseVersion(v) {
  const m = String(v || '').trim().replace(/^v/i, '').match(/^(\d+)(?:\.(\d+))?(?:\.(\d+))?(?:-([0-9A-Za-z.-]+))?/);
  if (!m) return null;
  return {
    nums: [+m[1], +(m[2] || 0), +(m[3] || 0)],
    pre: m[4] ? m[4].split('.').map((x) => (/^\d+$/.test(x) ? +x : x)) : [],
  };
}

// Semver precedence: <0 if a is older than b, 0 if equal, >0 if newer.
export function compareVersions(a, b) {
  const A = parseVersion(a), B = parseVersion(b);
  if (!A || !B) return 0;
  for (let i = 0; i < 3; i++) if (A.nums[i] !== B.nums[i]) return A.nums[i] - B.nums[i];
  if (!A.pre.length || !B.pre.length) return (A.pre.length ? -1 : 0) + (B.pre.length ? 1 : 0); // 1.0.0-rc < 1.0.0
  for (let i = 0; i < Math.max(A.pre.length, B.pre.length); i++) {
    const x = A.pre[i], y = B.pre[i];
    if (x === undefined) return -1;
    if (y === undefined) return 1;
    if (x === y) continue;
    if (typeof x === 'number' && typeof y === 'number') return x - y;
    if (typeof x === 'number') return -1;
    if (typeof y === 'number') return 1;
    return x < y ? -1 : 1;
  }
  return 0;
}
export const isNewer = (candidate, current) => compareVersions(candidate, current) > 0;

// Accepts a GitHub API release or the site's latest.json (same fields, simplified).
export function normalizeRelease(r) {
  if (!r || typeof r !== 'object') return null;
  const tag = r.tag_name || r.tag || (r.version ? 'v' + String(r.version).replace(/^v/, '') : '');
  if (!parseVersion(tag) || r.draft) return null;
  return {
    version: tag.replace(/^v/i, ''),
    tag,
    name: r.name || `Motivo ${tag}`,
    notes: String(r.body ?? r.notes ?? ''),
    url: r.html_url || r.url || RELEASES_PAGE,
    publishedAt: r.published_at || r.publishedAt || null,
    prerelease: !!r.prerelease,
    assets: (r.assets || []).map((a) => ({ name: a.name, url: a.browser_download_url || a.url, size: a.size || 0 })).filter((a) => a.name && a.url),
  };
}

// os: 'Darwin' | 'Windows' | 'Linux' (Neutralino's NL_OS); arch: 'x64' | 'arm64' | 'arm' | 'ia32'…
export function platformKey(os, arch) {
  if (/darwin|mac/i.test(os)) return 'mac';
  if (/win/i.test(os)) return 'win';
  if (/linux/i.test(os)) return arch === 'arm64' ? 'linux-arm64' : /^arm/.test(arch || '') ? 'linux-armhf' : 'linux-x64';
  return null;
}
export const platformLabel = (key) => ({ mac: 'macOS', win: 'Windows', 'linux-x64': 'Linux', 'linux-arm64': 'Linux (ARM64)', 'linux-armhf': 'Linux (ARMv7)' }[key] || 'your system');

export function assetFor(release, os, arch) {
  const key = platformKey(os, arch);
  if (!release || !key) return null;
  return release.assets.find((a) => a.name === ASSET_NAMES[key]) || null;
}

// Release notes are Markdown written by us or generated by GitHub. Render a
// safe subset: headings, lists, bold, inline code and http(s) links. Everything
// else is escaped text.
export function renderNotes(md) {
  const esc = (s) => s.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
  const inline = (s) => esc(s)
    .replace(/`([^`]+)`/g, '<code>$1</code>')
    .replace(/\*\*([^*]+)\*\*/g, '<b>$1</b>')
    .replace(/\[([^\]]+)\]\((https?:\/\/[^\s)]+)\)/g, (m, t, u) => `<a href="${u}" data-external>${t}</a>`)
    .replace(/(^|[\s(])(https:\/\/github\.com\/[\w.-]+\/[\w.-]+\/(?:pull|issues)\/(\d+))(?=[\s).,]|$)/g, (m, pre, u, n) => `${pre}<a href="${u}" data-external>#${n}</a>`)
    .replace(/(^|[\s(])(https?:\/\/[^\s<)]+)/g, (m, pre, u) => `${pre}<a href="${u}" data-external>${u}</a>`);
  const out = [];
  let list = false;
  for (const raw of String(md || '').replace(/\r\n?/g, '\n').split('\n')) {
    const line = raw.trimEnd();
    const h = line.match(/^#{1,6}\s+(.*)$/), li = line.match(/^\s*[-*+]\s+(.*)$/);
    if (li) { if (!list) { out.push('<ul>'); list = true; } out.push(`<li>${inline(li[1])}</li>`); continue; }
    if (list) { out.push('</ul>'); list = false; }
    if (h) out.push(`<h4>${inline(h[1])}</h4>`);
    else if (line.trim() && !/^<!--.*-->$/.test(line.trim())) out.push(`<p>${inline(line)}</p>`);
  }
  if (list) out.push('</ul>');
  return out.join('');
}
